export type DictKey = keyof Dict;

import { enUS } from "./en-US";
import { viVN } from "./vi-VN";
import { zhCN } from "./zh-CN";

export const DICTS: Record<Locale, Dict> = { "en-US": enUS, "vi-VN": viVN, "zh-CN": zhCN };

export const LOCALES: Locale[] = ["en-US", "vi-VN", "zh-CN"];

let current: Locale = "en-US";

export function setLocale(l: Locale): void {
  current = DICTS[l] ? l : "en-US";
}

export function getLocale(): Locale {
  return current;
}

// t("key", fallback?) — missing key falls back to en-US, never hardcoded prose.
export function t(key: DictKey, vars?: Record<string, string | number>): string {
  const dict = DICTS[current] ?? DICTS["en-US"];
  let s = dict[key] ?? DICTS["en-US"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
